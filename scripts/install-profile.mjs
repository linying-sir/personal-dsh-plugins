#!/usr/bin/env node
// Install the plugins listed in plugins/manifest.json into a DSH profile.
//
// Default is a dry run: it prints every command and the exact patch block it
// would write. Pass --apply to make the changes. The script backs up the
// profile's package.json and cordis.patch.yml before touching them.

import { spawnSync } from "node:child_process";
import { copyFileSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const BEGIN = "# >>> personal-dsh-plugins managed block";
const END = "# <<< personal-dsh-plugins managed block";

/** Parse `--flag value` and `--flag` arguments. */
function parseArgs(argv) {
  const options = {};
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (!argument.startsWith("--")) throw new Error(`unexpected argument: ${argument}`);
    const key = argument.slice(2);
    if (key === "apply" || key === "help" || key === "skip-install") {
      options[key] = true;
      continue;
    }
    const value = argv[index + 1];
    if (value === undefined || value.startsWith("--")) throw new Error(`missing value for ${argument}`);
    options[key] = value;
    index += 1;
  }
  return options;
}

/** Stop with a readable error. */
function fail(message) {
  console.error(`error: ${message}`);
  process.exit(1);
}

/** Print the usage text. */
function help() {
  console.log(`Usage: node scripts/install-profile.mjs [options]

Options:
  --profile <name>  DSH profile to install into (default: manifest profile, "desktop")
  --home <path>     DSH home directory (default: $DSH_HOME or ~/.dsh)
  --dsh <path>      dsh CLI executable (auto-detected from the Desktop install)
  --apply           write the changes; without it the script only prints the plan
  --skip-install    do not run \`dsh plugin add\`; only write the patch and bundle list
  --help            show this help
`);
}

/** Escape a string for use inside a RegExp. */
function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

/** Remove the managed block, if present. */
function withoutManagedBlock(text) {
  const begin = text.indexOf(BEGIN);
  const end = text.indexOf(END);
  if (begin < 0 || end < begin) return text;
  return text.slice(0, begin) + text.slice(end + END.length);
}

/** Build the managed block for the local path plugins. */
function buildManagedBlock(pathPlugins) {
  const lines = [
    BEGIN,
    "# Generated by scripts/install-profile.mjs; absolute paths are for this machine.",
    "# Re-run the installer after moving the repository.",
    "- insert:",
  ];
  for (const plugin of pathPlugins) {
    lines.push(`    - id: ${plugin.id}`);
    lines.push(`      name: '${plugin.name.replaceAll("'", "''")}'`);
  }
  lines.push(END);
  return lines.join("\n");
}

/** Put the managed block at the end of the patch, replacing an older one. */
function withManagedBlock(text, block) {
  const begin = text.indexOf(BEGIN);
  const end = text.indexOf(END);
  if (begin >= 0 && end >= begin) {
    return text.slice(0, begin) + block + text.slice(end + END.length);
  }
  if (begin >= 0 || end >= 0) {
    throw new Error("cordis.patch.yml has only one managed-block marker; restore it or remove the stray marker");
  }
  // A brand-new profile's patch file is often just `[]` (an empty YAML
  // sequence). Appending `- insert:` after that would be invalid YAML, so
  // drop the standalone empty sequence first.
  const base = text.replace(/^\s*\[\]\s*$/m, "");
  const trimmed = base.replace(/\s+$/, "");
  return trimmed === "" ? `${block}\n` : `${trimmed}\n\n${block}\n`;
}

/** Quote one argument for cmd.exe. */
function quote(value) {
  return `"${value.replaceAll('"', '""')}"`;
}

/** Run a child process and fail on a non-zero exit. */
function run(command, args, options = {}) {
  console.log(`$ ${[command, ...args].join(" ")}`);
  const result = spawnSync(command, args, { stdio: "inherit", ...options });
  if (result.error) fail(`could not run ${command}: ${result.error.message}`);
  if (result.status !== 0) fail(`${command} exited with code ${result.status}`);
}

/** Find the dsh CLI. */
function findDsh(explicit) {
  if (explicit !== undefined) {
    if (!existsSync(explicit)) fail(`dsh CLI not found: ${explicit}`);
    return explicit;
  }
  if (process.env.DSH_CLI !== undefined && process.env.DSH_CLI.trim() !== "") {
    return process.env.DSH_CLI;
  }
  const candidates = [];
  if (process.platform === "win32") {
    if (process.env.LOCALAPPDATA !== undefined) {
      candidates.push(
        join(
          process.env.LOCALAPPDATA,
          "Programs",
          "DeepSeek Harness",
          "resources",
          "runtime",
          "cli",
          "bin",
          "dsh.cmd",
        ),
      );
    }
    candidates.push("C:\\Program Files\\DeepSeek Harness\\resources\\runtime\\cli\\bin\\dsh.cmd");
  } else {
    candidates.push("/usr/local/bin/dsh", "/usr/bin/dsh");
  }
  for (const candidate of candidates) {
    if (existsSync(candidate)) return candidate;
  }
  const probe = spawnSync(process.platform === "win32" ? "where.exe" : "which", ["dsh"], {
    encoding: "utf8",
  });
  if (probe.status === 0) {
    const first = probe.stdout
      .split(/\r?\n/)
      .map((line) => line.trim())
      .find((line) => line !== "");
    if (first !== undefined) return first;
  }
  return null;
}

/** Run `dsh plugin ...`, handling the Windows .cmd shim. */
function runDsh(cli, args) {
  if (/\.(cmd|bat)$/i.test(cli)) {
    const commandLine = [cli, ...args].map(quote).join(" ");
    run(process.env.ComSpec ?? "cmd.exe", ["/d", "/s", "/c", commandLine]);
    return;
  }
  run(cli, args);
}

// ---- arguments and inventory -------------------------------------------------

let options;
try {
  options = parseArgs(process.argv.slice(2));
} catch (error) {
  fail(error instanceof Error ? error.message : String(error));
}

if (options.help === true) {
  help();
  process.exit(0);
}

const manifestPath = join(root, "plugins", "manifest.json");
if (!existsSync(manifestPath)) fail(`manifest not found: ${manifestPath}`);
const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
const profileName = options.profile ?? manifest.profile ?? "desktop";
const dshHome = resolve(options.home ?? process.env.DSH_HOME ?? join(homedir(), ".dsh"));
const profileDirectory = join(dshHome, "profiles", profileName);
const profileManifestPath = join(profileDirectory, "package.json");
const patchPath = join(profileDirectory, "cordis.patch.yml");

if (!existsSync(profileManifestPath)) {
  fail(
    `profile "${profileName}" not found at ${profileDirectory}. ` +
      "Start DSH once with that profile so it creates the directory, or pass --profile.",
  );
}

const pathPlugins = [];
const packagePlugins = [];
const bundleInstalls = [];
const bundleNames = new Set();

for (const entry of manifest.plugins ?? []) {
  if (entry.kind === "path") {
    const id = entry.id ?? entry.dir;
    if (typeof entry.dir !== "string" || entry.dir.trim() === "") {
      fail("manifest: a path plugin is missing dir");
    }
    const directory = join(root, "plugins", entry.dir);
    const packagePath = join(directory, "package.json");
    if (!existsSync(packagePath)) fail(`manifest: plugins/${entry.dir}/package.json is missing`);
    const packageManifest = JSON.parse(readFileSync(packagePath, "utf8"));
    const main = packageManifest.main ?? "lib/index.js";
    const entryPath = join(directory, main);
    if (!existsSync(entryPath)) fail(`manifest: ${entryPath} is missing`);
    pathPlugins.push({ id, name: entryPath.replaceAll("\\", "/") });
    if (entry.bundle === true) {
      bundleInstalls.push(directory);
      bundleNames.add(packageManifest.name);
    }
    continue;
  }
  if (entry.kind === "package") {
    if (typeof entry.name !== "string" || entry.name.trim() === "") {
      fail("manifest: a package plugin is missing name");
    }
    packagePlugins.push(entry);
    if (entry.bundle === true) bundleNames.add(entry.name);
    continue;
  }
  fail(`manifest: unknown kind "${entry.kind}"`);
}

// ---- plan --------------------------------------------------------------------

console.log("personal-dsh-plugins installer");
console.log(`  repository: ${root}`);
console.log(`  profile:    ${profileDirectory}`);
console.log(`  mode:       ${options.apply === true ? "apply" : "dry run (pass --apply to write)"}`);
console.log("");

if (pathPlugins.length > 0) {
  console.log("Local plugins (managed patch block):");
  for (const plugin of pathPlugins) console.log(`  - ${plugin.id} -> ${plugin.name}`);
} else {
  console.log("Local plugins: none");
}

if (packagePlugins.length > 0 || bundleInstalls.length > 0) {
  console.log("");
  console.log("Package installs (`dsh plugin add`):");
  for (const plugin of packagePlugins) {
    const spec = plugin.version === undefined ? plugin.name : `${plugin.name}@${plugin.version}`;
    console.log(`  - ${spec}${plugin.bundle === true ? " (bundle)" : ""}`);
  }
  for (const directory of bundleInstalls) {
    console.log(`  - ${directory} (local bundle)`);
  }
}

if (bundleNames.size > 0) {
  console.log("");
  console.log("Bundle list additions:");
  for (const name of bundleNames) console.log(`  - ${name}`);
}

const patchText = existsSync(patchPath) ? readFileSync(patchPath, "utf8") : "[]\n";
const block = pathPlugins.length > 0 ? buildManagedBlock(pathPlugins) : "";
const outsideBlock = withoutManagedBlock(patchText);
for (const plugin of pathPlugins) {
  const duplicate = new RegExp(
    `^\\s*-\\s*id:\\s*['"]?${escapeRegExp(plugin.id)}['"]?\\s*$`,
    "m",
  ).test(outsideBlock);
  if (duplicate) {
    fail(
      `cordis.patch.yml already contains id "${plugin.id}" outside the managed block. ` +
        "Remove that entry first so the installer does not create a duplicate.",
    );
  }
}

console.log("");
console.log("Patch block to write:");
console.log(block === "" ? "  (none)" : block);

if (options.apply !== true) {
  console.log("");
  console.log("Dry run complete. Re-run with --apply to install.");
  process.exit(0);
}

// ---- apply -------------------------------------------------------------------

const stamp = new Date().toISOString().replace(/[:.]/g, "-");
for (const file of [patchPath, profileManifestPath]) {
  if (existsSync(file)) {
    const backup = `${file}.bak-personal-plugins-${stamp}`;
    copyFileSync(file, backup);
    console.log(`backup: ${backup}`);
  }
}

const needsDsh = (packagePlugins.length > 0 || bundleInstalls.length > 0) && options["skip-install"] !== true;
const dshCli = needsDsh ? findDsh(options.dsh) : null;
if (needsDsh && dshCli === null) {
  fail("dsh CLI not found; pass --dsh <path> or set DSH_CLI");
}

if (options["skip-install"] !== true) {
  for (const plugin of packagePlugins) {
    const spec = plugin.version === undefined ? plugin.name : `${plugin.name}@${plugin.version}`;
    runDsh(dshCli, ["plugin", "--profile", profileName, "add", spec]);
  }
  for (const directory of bundleInstalls) {
    runDsh(dshCli, ["plugin", "--profile", profileName, "add", directory]);
  }
}

if (bundleNames.size > 0) {
  const profileManifest = JSON.parse(readFileSync(profileManifestPath, "utf8"));
  profileManifest.dsh ??= {};
  profileManifest.dsh.profile ??= {};
  const current = Array.isArray(profileManifest.dsh.profile.bundles)
    ? profileManifest.dsh.profile.bundles
    : [];
  const next = [...current];
  for (const name of bundleNames) {
    if (!next.includes(name)) next.push(name);
  }
  if (next.length !== current.length) {
    profileManifest.dsh.profile.bundles = next;
    writeFileSync(profileManifestPath, `${JSON.stringify(profileManifest, null, 2)}\n`);
    console.log(`updated: ${profileManifestPath}`);
  }
}

const nextPatch = block === "" ? withoutManagedBlock(patchText) : withManagedBlock(patchText, block);
if (nextPatch !== patchText) {
  writeFileSync(patchPath, nextPatch);
  console.log(`updated: ${patchPath}`);
}

console.log("");
console.log("Done. Quit DSH from the tray and start it again.");
